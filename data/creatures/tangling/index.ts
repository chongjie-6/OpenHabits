/** A guardian and its evolved form, which `forms` lists side by side. */
function pair(
  id: string,
  evolvesAt: number,
  stats: Pick<Line, "kind" | "alignment" | "abilities" | "skills">,
  moves: Move[],
): Line {
  const at = forms.findIndex((form) => form.id === id);
  return {
    id,
    forms: forms.slice(at, at + 2),
    evolvesAt: [evolvesAt],
    moves,
    ...stats,
  };
}

